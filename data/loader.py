"""
data/loader.py — Parse Excel dataset into canonical Python structures.

Loading priority:
  1. data/dataset.json  — cleaned/normalised values (generated by data/clean_dataset.py)
  2. config.EXCEL_PATH  — raw Excel (fallback if JSON not present)
"""

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import pandas as pd

import config

config.DATA_DIR.mkdir(parents=True, exist_ok=True)

_DATASET_JSON = config.DATA_DIR / "dataset.json"


# ─── Data classes ─────────────────────────────────────────────────────────────

@dataclass
class Extraction:
    prop_id:          int
    example_id:       int
    doi:              str
    text:             str
    chemical_name:    str
    value:            str
    unit:             str
    property_label:   str   # normalised lowercase
    covariate_value:  Optional[str]
    covariate_unit:   Optional[str]
    covariate_type:   Optional[str]
    name_type:        str
    group:            str
    split:            str   # "train" | "test"
    text_id:          str = ""  # unique per text passage: "{doi}#{example_id}"

    def to_dict(self) -> dict:
        return self.__dict__.copy()


@dataclass
class Document:
    doi:        str
    text:       str
    prop_ids:   list[int]
    split:      str = "unknown"
    text_id:    str = ""   # unique per text passage: "{doi}#{example_id}"
    extractions: list[Extraction] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "doi": self.doi,
            "text_id": self.text_id,
            "text": self.text,
            "prop_ids": self.prop_ids,
            "split": self.split,
            "extractions": [e.to_dict() for e in self.extractions],
        }


# ─── Helpers ──────────────────────────────────────────────────────────────────

def _norm_label(raw) -> str:
    s = re.sub(r"[\[\]'\"]", "", str(raw)).strip().lower()
    for canonical, aliases in config.PROPERTY_SYNONYMS.items():
        if s in aliases:
            return canonical
    return s


# ─── Main loader ──────────────────────────────────────────────────────────────

def _load_from_json(json_path: Path) -> dict:
    """Load the pre-cleaned dataset.json produced by data/clean_dataset.py."""
    with open(json_path, encoding="utf-8") as f:
        payload = json.load(f)

    extractions: list[Extraction] = []
    for row in payload.get("extractions", []):
        doi        = str(row["doi"]).strip()
        example_id = int(row["example_id"])
        text_id    = str(row.get("text_id", "")) or f"{doi}#{example_id}"
        extractions.append(Extraction(
            prop_id        = int(row["prop_id"]),
            example_id     = example_id,
            doi            = doi,
            text           = str(row["text"]),
            chemical_name  = str(row["chemical_name"]).strip(),
            value          = str(row.get("value", "")).strip(),
            unit           = str(row.get("unit", "")).strip(),
            property_label = row["property_label"],
            covariate_value= row.get("covariate_value"),
            covariate_unit = row.get("covariate_unit"),
            covariate_type = row.get("covariate_type"),
            name_type      = str(row.get("name_type", "unknown")),
            group          = str(row.get("group", "unknown")),
            split          = str(row.get("split", "test")),
            text_id        = text_id,
        ))

    # Group by (doi, text) so that two example_ids with the same text in the
    # same DOI become one Document (their GT extractions are combined).
    # text_id is taken from the first example_id encountered for that (doi, text).
    doc_map: dict[tuple, Document] = {}
    for e in extractions:
        key = (e.doi, e.text)
        if key not in doc_map:
            doc_map[key] = Document(doi=e.doi, text=e.text, prop_ids=[], text_id=e.text_id)
        doc = doc_map[key]
        if e.prop_id not in doc.prop_ids:
            doc.prop_ids.append(e.prop_id)
        doc.extractions.append(e)

    for doc in doc_map.values():
        train = [p for p in doc.prop_ids if p in config.TRAIN_PROPERTY_IDS]
        test  = [p for p in doc.prop_ids if p in config.TEST_PROPERTY_IDS]
        doc.split = "train" if (train and not test) else "test" if (test and not train) else "mixed"

    documents  = list(doc_map.values())
    train_docs = [d for d in documents if d.split == "train"]
    test_docs  = [d for d in documents if d.split == "test"]

    print(f"[Loader] {len(extractions)} extractions | {len(documents)} documents | "
          f"{len(train_docs)} train | {len(test_docs)} test  (source: dataset.json)")
    return {"extractions": extractions, "documents": documents,
            "train_docs": train_docs, "test_docs": test_docs}


def load_dataset(excel_path: Path = None) -> dict:
    # Prefer cleaned JSON if it exists and no explicit Excel path is given
    if excel_path is None and _DATASET_JSON.exists():
        return _load_from_json(_DATASET_JSON)

    excel_path = excel_path or config.EXCEL_PATH
    df = pd.read_excel(excel_path, sheet_name="Index List AI4CHEMIA", header=0)
    df.columns = [
        "prop_id", "example_id", "doi", "text",
        "chemical_name", "value", "unit", "property_label",
        "cov_value", "cov_unit", "cov_type",
        "word_count", "name_len", "name_type", "group",
    ]

    df["prop_id"]    = pd.to_numeric(df["prop_id"],    errors="coerce").ffill()
    df["example_id"] = pd.to_numeric(df["example_id"], errors="coerce").ffill()
    df["doi"]  = df["doi"].ffill()
    df["text"] = df["text"].ffill()

    df = df[df["chemical_name"].notna()].copy()
    df = df[~df["chemical_name"].astype(str).str.startswith("=")].copy()
    df["prop_id"]    = df["prop_id"].astype(int)
    df["example_id"] = df["example_id"].astype(int)
    df["property_label_clean"] = df["property_label"].apply(_norm_label)
    df["split"] = df["prop_id"].apply(
        lambda x: "train" if x in config.TRAIN_PROPERTY_IDS else "test"
    )

    extractions: list[Extraction] = []
    for _, row in df.iterrows():
        doi        = str(row["doi"]).strip()
        example_id = int(row["example_id"])
        extractions.append(Extraction(
            prop_id       = int(row["prop_id"]),
            example_id    = example_id,
            doi           = doi,
            text          = str(row["text"]),
            chemical_name = str(row["chemical_name"]).strip(),
            value         = str(row["value"]).strip() if pd.notna(row["value"]) else "",
            unit          = str(row["unit"]).strip()  if pd.notna(row["unit"])  else "",
            property_label= row["property_label_clean"],
            covariate_value= str(row["cov_value"]) if pd.notna(row["cov_value"]) else None,
            covariate_unit = str(row["cov_unit"])  if pd.notna(row["cov_unit"])  else None,
            covariate_type = str(row["cov_type"]).lower() if pd.notna(row["cov_type"]) else None,
            name_type     = str(row["name_type"]) if pd.notna(row["name_type"]) else "unknown",
            group         = str(row["group"])     if pd.notna(row["group"])     else "unknown",
            split         = row["split"],
            text_id       = f"{doi}#{example_id}",
        ))

    # Group by (doi, text) — same text in same DOI → one Document
    doc_map: dict[tuple, Document] = {}
    for e in extractions:
        key = (e.doi, e.text)
        if key not in doc_map:
            doc_map[key] = Document(doi=e.doi, text=e.text, prop_ids=[], text_id=e.text_id)
        doc = doc_map[key]
        if e.prop_id not in doc.prop_ids:
            doc.prop_ids.append(e.prop_id)
        doc.extractions.append(e)

    for doc in doc_map.values():
        train = [p for p in doc.prop_ids if p in config.TRAIN_PROPERTY_IDS]
        test  = [p for p in doc.prop_ids if p in config.TEST_PROPERTY_IDS]
        doc.split = "train" if (train and not test) else "test" if (test and not train) else "mixed"

    documents  = list(doc_map.values())
    train_docs = [d for d in documents if d.split == "train"]
    test_docs  = [d for d in documents if d.split == "test"]

    print(f"[Loader] {len(extractions)} extractions | {len(documents)} documents | "
          f"{len(train_docs)} train | {len(test_docs)} test")

    return {
        "extractions": extractions,
        "documents":   documents,
        "train_docs":  train_docs,
        "test_docs":   test_docs,
    }


def get_property_name_map(data: dict) -> dict[int, dict]:
    """
    Returns {prop_id: {"property_label": str, "tier": str}} from a loaded dataset.
    """
    result: dict[int, dict] = {}
    for ext in data.get("extractions", []):
        pid = ext.prop_id
        if pid not in result:
            result[pid] = {
                "property_label": ext.property_label,
                "tier":           ext.split,   # "train" | "test"
                "group":          ext.group,
            }
    return result


def save_dataset_json(data: dict, path: Path = None):
    path = path or (config.DATA_DIR / "dataset.json")
    payload = {
        "train": [d.to_dict() for d in data["train_docs"]],
        "test":  [d.to_dict() for d in data["test_docs"]],
    }
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
    print(f"[Loader] Dataset saved -> {path}")
